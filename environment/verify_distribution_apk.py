"""Read-only APK/source audit with explicit profile and dynamic build identity.

This never installs, launches, builds or signs an app. The caller chooses the
exact personal, public-demo or injected QA source tree being audited.
"""
import argparse
import hashlib
from io import BytesIO
import json
from pathlib import Path
import sys
import tempfile
import tomllib
from types import SimpleNamespace
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from app_build_identity import load_identity, verify_apk
from inspect_app_apk import inspect_python_module

PACKAGES = {'personal': 'org.example.kanamemory', 'demo': 'org.example.demo.kanamemory',
            'qa': 'org.example.qa.kanamemory'}


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def expected_metadata(app_source, identity):
    """The four observed Briefcase metadata files, generated by its writer.

    Nothing else outside module bytecode and the chosen resources is allowed.
    Platform newline differences are normalized only for this text metadata.
    """
    from briefcase.commands.create import write_dist_info
    config = tomllib.loads((Path(app_source) / 'pyproject.toml').read_text('utf-8'))['tool']['briefcase']
    app = config['app']['kanamemory']
    config = {**config, **app, **app.get('android', {})}
    values = SimpleNamespace(app_name='kanamemory', module_name='kanamemory',
        formal_name=config['formal_name'], bundle_identifier=identity['package_id'],
        version=identity['version'], url=config.get('url'), author=config.get('author'),
        author_email=config.get('author_email'), description=config.get('description', ''))
    prefix = 'kanamemory-' + identity['version'] + '.dist-info'
    scratch = ROOT / '.test_runs'
    scratch.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='kanamemory-metadata-', dir=scratch) as folder:
        if not Path(folder).resolve().is_relative_to(scratch.resolve()):
            raise ValueError('Metadata scratch directory escaped its selected workspace')
        destination = Path(folder) / prefix
        write_dist_info(values, destination)
        return {prefix + '/' + p.name: p.read_bytes().replace(b'\r\n', b'\n') for p in destination.iterdir()}


def verify(apk, app_source, aapt, *, profile):
    apk, app_source = Path(apk), Path(app_source)
    identity = load_identity(app_source)
    if profile not in PACKAGES or identity['package_id'] != PACKAGES[profile]:
        raise ValueError('Source package does not match the explicitly selected profile')
    verify_apk(apk, aapt, identity)
    fingerprint = sha(apk)
    source_root = app_source / 'src'
    module_root = source_root / 'kanamemory'
    expected_modules = {p.relative_to(source_root).with_suffix('.pyc').as_posix()
                        for p in module_root.rglob('*.py') if '__pycache__' not in p.parts}
    resources = module_root / 'resources'
    expected_resources = {p.relative_to(source_root).as_posix(): sha(p)
                          for p in resources.rglob('*') if p.is_file()}
    metadata = expected_metadata(app_source, identity)
    with zipfile.ZipFile(apk) as outer:
        with zipfile.ZipFile(BytesIO(outer.read('assets/chaquopy/app.imy'))) as inner:
            names = [entry.filename for entry in inner.infolist() if not entry.is_dir()]
            if len(names) != len(set(names)):
                raise ValueError('Duplicate application archive members')
            if set(names) != expected_modules | set(expected_resources) | set(metadata):
                raise ValueError('APK application inventory contains extra or missing files')
            if any(inner.read(name).replace(b'\r\n', b'\n') != value for name, value in metadata.items()):
                raise ValueError('APK build metadata differs from the selected source or build tool')
            modules = {name for name in names if name.startswith('kanamemory/') and name.endswith('.pyc')}
            if modules != expected_modules:
                raise ValueError('APK Python module inventory differs from the selected source')
            checks = [inspect_python_module(name, inner.read(name), source_root) for name in sorted(modules)]
            if not all(row['compiled_code_matches_workspace'] is True for row in checks):
                raise ValueError('APK Python bytecode is stale or uses a different Python version')
            actual_resources = {name: hashlib.sha256(inner.read(name)).hexdigest()
                                for name in names if name.startswith('kanamemory/resources/')}
            if actual_resources != expected_resources:
                raise ValueError('APK resources differ from the selected content pack')
    if profile == 'demo':
        from check_public_content import validate_apk
        validate_apk(apk, resources, source=app_source.parent / 'demo/content.json')
    if sha(apk) != fingerprint:
        raise ValueError('APK changed during verification')
    return {'format': 'kanamemory-distribution-apk-audit-v1', 'passed': True, 'profile': profile,
        'identity': identity, 'apk_sha256': fingerprint, 'apk_bytes': apk.stat().st_size,
        'python_modules': len(checks), 'module_checks': checks,
        'resource_sha256': actual_resources, 'demo_content_boundary_checked': profile == 'demo',
        'complete_application_inventory_checked': True,
        'build_metadata_sha256': {name: hashlib.sha256(value).hexdigest() for name, value in metadata.items()},
        'device_touched': False, 'build_performed': False,
        'limits': ['Bytecode equivalence does not certify source comments.',
                   'Signature, ELF alignment and native runtime behavior need their separate checks.']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', choices=PACKAGES, required=True)
    parser.add_argument('--app-source', type=Path, required=True)
    parser.add_argument('--apk', type=Path, required=True)
    parser.add_argument('--aapt', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    if args.report.exists():
        raise FileExistsError('Use a fresh report; previous evidence is never overwritten')
    report = verify(args.apk, args.app_source, args.aapt, profile=args.profile)
    with args.report.open('x', encoding='utf-8', newline='\n') as stream:
        json.dump(report, stream, ensure_ascii=False, indent=2)
        stream.write('\n')
    print(json.dumps({key: report[key] for key in ('passed', 'identity', 'apk_sha256', 'python_modules')}))


if __name__ == '__main__':
    main()
